"""Serves the React POS at /pos (and every /pos/... deep link, see website_route_rules).

`pos.html` is generated by `yarn build` in Tijao-POS/frontend; don't edit it by hand.

Login is handled inside the React app (/pos/login), not by redirecting here:
one bundle, deep links keep working, and an expired session mid-sale can be
handled in place without losing the cart.
"""

import frappe

no_cache = 1


def get_context(context):
	context.no_cache = 1
	# Handed to the SPA for X-Frappe-CSRF-Token. Guests get none; they log in first,
	# and auth.me returns the fresh token for the new session.
	context.csrf_token = frappe.sessions.get_csrf_token() if frappe.session.user != "Guest" else ""
	return context
